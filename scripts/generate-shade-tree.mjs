// Generates public/textures/shade-tree.svg — a broad shade-tree silhouette
// (the tree on the TIM ATIEP cover). It is a shape only: components use it as
// a CSS mask and paint it with theme colours. Run: node scripts/generate-shade-tree.mjs
import { writeFileSync } from "node:fs";

function mulberry32(seed) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(2026);
const between = (a, b) => a + rand() * (b - a);
const f = (n) => Math.round(n);
const limbs = [];
const blobs = [];
const box = { minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity };
const grow = (x, y, pad = 0) => {
  box.minX = Math.min(box.minX, x - pad); box.maxX = Math.max(box.maxX, x + pad);
  box.minY = Math.min(box.minY, y - pad); box.maxY = Math.max(box.maxY, y + pad);
};

// Tapered segment as a quad. Every quad winds the same way, so overlaps union cleanly.
function limb(x0, y0, x1, y1, w0, w1) {
  const len = Math.hypot(x1 - x0, y1 - y0) || 1;
  const nx = -(y1 - y0) / len, ny = (x1 - x0) / len;
  limbs.push(
    `M${f(x0 + (nx * w0) / 2)} ${f(y0 + (ny * w0) / 2)}L${f(x1 + (nx * w1) / 2)} ${f(y1 + (ny * w1) / 2)}` +
      `L${f(x1 - (nx * w1) / 2)} ${f(y1 - (ny * w1) / 2)}L${f(x0 - (nx * w0) / 2)} ${f(y0 - (ny * w0) / 2)}Z`,
  );
  blob(x1, y1, w1 / 2);
  grow(x0, y0, w0); grow(x1, y1, w1);
}

function blob(cx, cy, r) {
  blobs.push(`M${f(cx - r)} ${f(cy)}a${f(r)} ${f(r)} 0 1 0 ${f(2 * r)} 0a${f(r)} ${f(r)} 0 1 0 ${f(-2 * r)} 0Z`);
  grow(cx, cy, r);
}

function branch(x, y, angle, length, width, depth) {
  const endWidth = width * 0.62;
  let cx = x, cy = y, a = angle;
  for (let i = 0; i < 2; i++) {
    a += between(-0.14, 0.14);
    const nx = cx + (Math.cos(a) * length) / 2;
    const ny = cy - (Math.sin(a) * length) / 2;
    limb(cx, cy, nx, ny, width + ((endWidth - width) * i) / 2, width + ((endWidth - width) * (i + 1)) / 2);
    cx = nx; cy = ny;
  }
  // Leaf mass — the shade itself. Clusters grow inside the crown too, not just
  // at the tips, so the canopy reads as a full dome.
  if (depth === 0) {
    for (let i = 0; i < 3; i++) blob(cx + between(-26, 26), cy + between(-24, 10), between(20, 32));
    return;
  }
  if (depth === 1) for (let i = 0; i < 2; i++) blob(cx + between(-30, 30), cy + between(-30, 6), between(26, 40));
  if (depth === 2 && rand() < 0.7) blob(cx + between(-20, 20), cy - between(0, 24), between(30, 46));
  const count = depth >= 4 ? 2 : rand() < 0.4 ? 3 : 2;
  const spread = between(0.55, 0.85);
  for (let k = 0; k < count; k++) {
    let child = a - spread / 2 + (spread * k) / (count - 1) + between(-0.1, 0.1);
    // Shade trees spread wide: nudge each fork toward the horizontal.
    const horizon = Math.cos(child) >= 0 ? 0.3 : Math.PI - 0.3;
    child += (horizon - child) * 0.14;
    branch(cx, cy, child, length * between(0.72, 0.82), endWidth * 0.8, depth - 1);
  }
}

// Trunk with a gentle sway and a root flare.
const trunkTop = { x: 500, y: 560 };
limb(500, 1000, 492, 800, 128, 96);
limb(492, 800, 506, 660, 96, 78);
limb(506, 660, trunkTop.x, trunkTop.y, 78, 66);
limb(470, 975, 360, 1005, 46, 12);
limb(530, 975, 650, 1005, 46, 12);
limb(485, 985, 420, 1010, 30, 8);
limb(515, 985, 585, 1010, 30, 8);

// Main limbs fan out from the top of the trunk.
for (const [deg, len] of [[158, 200], [128, 190], [100, 150], [80, 150], [52, 190], [22, 200]]) {
  branch(trunkTop.x, trunkTop.y, (deg * Math.PI) / 180, len, 44, 5);
}

const pad = 10;
const vb = [box.minX - pad, box.minY - pad, box.maxX - box.minX + pad * 2, box.maxY - box.minY + pad * 2].map(f);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb.join(" ")}">
  <!-- Shade tree after the TIM ATIEP cover. Generated by scripts/generate-shade-tree.mjs. Used as a mask. -->
  <path d="${limbs.join("")}"/>
  <path d="${blobs.join("")}"/>
</svg>
`;
writeFileSync(new URL("../public/textures/shade-tree.svg", import.meta.url), svg);
// The scene drawn over the tree (shade, reader) shares this coordinate space.
writeFileSync(
  new URL("../components/ui/shadeTreeGeometry.ts", import.meta.url),
  `// Generated by scripts/generate-shade-tree.mjs — do not edit.\nexport const SHADE_TREE_VIEWBOX = "${vb.join(" ")}";\n`,
);
console.log(`shade-tree.svg: ${limbs.length} limbs, ${blobs.length} blobs, viewBox ${vb.join(" ")}, ${(svg.length / 1024).toFixed(0)} KB`);
